// These are raster source rectangles, not code-drawn graphics. All pixels are
// generated by ImageGen. The bounded cache retains only the bundled atlases.
final _atlases = <String, Future<ui.Image>>{};
final _decodedAtlases = <String, ui.Image>{};

/// A gesture can start immediately only when its atlas can already paint.
bool rasterArtworkIsReady(String path) => _decodedAtlases.containsKey(path);

/// Load shared sprite sheets before screenshot tests enter their fake clock.
Future<void> precacheRasterArtwork(Iterable<String> paths) async {
  await Future.wait(paths.map(_atlas));
}

// Integration screenshots must wait for real asset decoding, not only fake time.
Future<void> precacheFamilyArtwork(BuildContext context) async {
  await Future.wait([
    for (final name in ['logo-v1', 'coin-v1', 'book-v1'])
      precacheImage(AssetImage('assets/generated/$name.png'), context),
    _atlas('assets/generated/navigation-v1.png'),
    _atlas('assets/generated/activities-v2.png'),
    _atlas('assets/generated/helper-wave-v2.png'),
    _atlas('assets/generated/celebration-v2.png'),
    for (final name in ['book', 'extra', 'task'])
      _atlas('assets/generated/calendar-$name.png'),
  ]);
}

Future<ui.Image> _atlas(String path) => _atlases.putIfAbsent(path, () async {
  final data = await rootBundle.load(path);
  final codec = await ui.instantiateImageCodec(
    data.buffer.asUint8List(data.offsetInBytes, data.lengthInBytes),
  );
  try {
    final image = (await codec.getNextFrame()).image;
    _decodedAtlases[path] = image;
    return image;
  } finally {
    codec.dispose();
  }
});

class RasterSprite extends StatelessWidget {
  final String path;
  final Rect source;
  final double size;
  final bool normalized;
  final bool preserveAspectRatio;
  const RasterSprite({
    super.key,
    required this.path,
    required this.source,
    this.size = 32,
    this.normalized = false,
    this.preserveAspectRatio = false,
  });
  @override
  Widget build(BuildContext context) {
    Widget paint(ui.Image image) => CustomPaint(
      painter: _SpritePainter(
        image,
        normalized
            ? Rect.fromLTWH(
                source.left * image.width,
                source.top * image.height,
                source.width * image.width,
                source.height * image.height,
              )
            : source,
        preserveAspectRatio,
      ),
    );
    // A completed atlas can paint immediately. A new pending atlas must never
    // inherit FutureBuilder's retained image from the previous world.
    final decoded = _decodedAtlases[path];
    return ExcludeSemantics(
      child: SizedBox.square(
        dimension: size,
        child: decoded != null
            ? paint(decoded)
            : FutureBuilder<ui.Image>(
                key: ValueKey(path),
                future: _atlas(path),
                builder: (context, data) =>
                    data.hasData ? paint(data.data!) : const SizedBox.shrink(),
              ),
      ),
    );
  }
}

class _SpritePainter extends CustomPainter {
  final ui.Image image;
  final Rect source;
  final bool preserveAspectRatio;
  const _SpritePainter(this.image, this.source, this.preserveAspectRatio);
  @override
  void paint(Canvas canvas, Size size) => canvas.drawImageRect(
    image,
    source,
    preserveAspectRatio
        ? Alignment.center.inscribe(
            applyBoxFit(BoxFit.contain, source.size, size).destination,
            Offset.zero & size,
          )
        : Offset.zero & size,
    Paint()..filterQuality = FilterQuality.medium,
  );
  @override
  bool shouldRepaint(_SpritePainter old) =>
      old.image != image ||
      old.source != source ||
      old.preserveAspectRatio != preserveAspectRatio;
}

class FamilyIcon extends StatelessWidget {
  final int index;
  final double size;
  const FamilyIcon(this.index, {super.key, this.size = 32});
  @override
  Widget build(BuildContext context) {
    if (gameDesign.value != null) return GameIcon(index, size: size);
    if (index == 1 || index == 3) {
      return Image.asset(
        'assets/generated/${index == 1 ? 'book-v1' : 'coin-v1'}.png',
        width: size,
        height: size,
        fit: BoxFit.contain,
        excludeFromSemantics: true,
      );
    }
    return RasterSprite(
      path: 'assets/generated/navigation-v1.png',
      size: size,
      // The book in the source sheet reaches two pixels into the next cell.
      // Select only the checklist's own pixels; the bitmap is not modified.
      source: index == 2
          ? Rect.fromLTWH(index * 362 + 8, 180, 354, 362)
          : Rect.fromLTWH(index * 362, 180, 362, 362),
    );
  }
}

