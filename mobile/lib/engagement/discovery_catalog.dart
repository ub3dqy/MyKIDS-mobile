int discoveriesOpen(int confirmedTasks) =>
    spaceDiscoveries.where((stop) => confirmedTasks >= stop.tasks).length;

SpaceDiscovery? nextDiscovery(int confirmedTasks) =>
    spaceDiscoveries.where((stop) => stop.tasks > confirmedTasks).firstOrNull;

String discoveryTaskCount(int count) {
  final last = count % 100;
  final ending = last >= 11 && last <= 14
      ? 'дел'
      : switch (count % 10) {
          1 => 'дело',
          2 || 3 || 4 => 'дела',
          _ => 'дел',
        };
  return '$count $ending';
}
